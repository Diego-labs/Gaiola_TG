function salvar_campo_magnetico(Bn, Be, Bd, Btotal, nome_arquivo)
%--------------------------------------------------------------
%
% Salva o campo magnético calculado pelo IGRF em um arquivo CSV.
%
% Entradas:
%   Bn           -> componente Norte (uT)
%   Be           -> componente Leste (uT)
%   Bd           -> componente Down (uT)
%   Btotal       -> módulo do campo (uT)
%   nome_arquivo -> nome do arquivo CSV
%
%--------------------------------------------------------------

Tabela = table( ...
    Bn, ...
    Be, ...
    Bd, ...
    Btotal, ...
    'VariableNames', { ...
    'Bn_uT', ...
    'Be_uT', ...
    'Bd_uT', ...
    'Btotal_uT'});

writetable(Tabela, nome_arquivo);

end